import { useEffect, useState } from 'react';
import { useParams, Link } from 'react-router-dom';
import { feedApi, savedApi } from '../lib/api.js';
import type { Feed } from '../lib/api.js';
import { getUserEmail, getAvatarUrl } from '../lib/auth.js';

// ReadPage: full article view. Loads feed by slug, marks as saved if
// the user has it saved, and lets the user toggle save state inline.
export default function ReadPage() {
  const { slug } = useParams<{ slug: string }>();
  const [feed, setFeed] = useState<Feed | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [saved, setSaved] = useState(false);
  const email = getUserEmail();

  useEffect(() => {
    let cancelled = false;
    setFeed(null);
    setError(null);
    (async () => {
      try {
        if (!slug) return;
        const res = await feedApi.getFeedItem(slug);
        if (cancelled) return;
        setFeed(res.feed);
        if (email) {
          try {
            const s = await savedApi.checkSaved(email, res.feed.id);
            if (!cancelled) setSaved(!!s.saved);
          } catch (e) {
            // non-fatal
          }
        }
      } catch (err) {
        if (!cancelled) setError(err instanceof Error ? err.message : 'Unknown error');
      }
    })();
    return () => { cancelled = true; };
  }, [slug, email]);

  const toggleSave = async () => {
    if (!email || !feed) return;
    try {
      if (saved) {
        await savedApi.unsaveFeed(email, feed.id);
        setSaved(false);
      } else {
        await savedApi.saveFeed(email, feed.id);
        setSaved(true);
      }
    } catch (err) {
      console.error('Save toggle failed:', err);
    }
  };

  if (error) {
    return (
      <main className="main">
        <div className="read-error">Could not load article: {error}</div>
        <Link to="/feed" className="read-back">← Back to feed</Link>
      </main>
    );
  }
  if (!feed) {
    return (
      <main className="main">
        <div className="read-loading">
          <div className="spinner" />
        </div>
      </main>
    );
  }

  return (
    <main className="main read-main">
      <article className="read-article">
        {feed.image_url && (
          <div className="read-cover">
            <img src={feed.image_url} alt={feed.title || ''} />
          </div>
        )}
        <header className="read-header">
          <h1 className="read-title">{feed.title || '(Untitled)'}</h1>
          <div className="read-meta">
            <img
              className="read-avatar"
              src={feed.author_avatar || getAvatarUrl(feed.author || 'anon')}
              alt={feed.author || ''}
            />
            <div className="read-meta-text">
              <div className="read-author">{feed.author || 'Anonymous'}</div>
              <div className="read-sub">
                {feed.read_time || 5} min read · {feed.created_at}
              </div>
            </div>
            {email && (
              <button
                type="button"
                className={`read-save-btn${saved ? ' saved' : ''}`}
                onClick={toggleSave}
              >
                {saved ? 'Saved' : 'Save'}
              </button>
            )}
          </div>
        </header>
        <div
          className="read-content"
          // feed.content is HTML generated by editorBlocksToHtml on the
          // writer screen, then stored verbatim in the DB.
          dangerouslySetInnerHTML={{ __html: feed.content || '' }}
        />
        {Array.isArray(feed.tags) && feed.tags.length > 0 && (
          <div className="read-tags">
            {feed.tags.map((t: string) => (
              <span key={t} className="read-tag">#{t}</span>
            ))}
          </div>
        )}
      </article>
    </main>
  );
}
